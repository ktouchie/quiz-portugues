/**
 * Every interface text in the app, in one language. Same wording as the web app's i18n.js;
 * the Portuguese being learnt (words, verb forms, tense names) is never in here.
 */
class Strings(
    // Shared
    val loading: String,
    val correct: String,
    val rightAnswer: (String) -> String,
    val example: (String) -> String,
    val continueLabel: String,
    val answer: String,
    val accentTip: String,
    val progressSummary: (correct: Int, wrong: Int) -> String,
    // Results
    val sessionDone: String,
    val statTime: String,
    val statCorrect: String,
    val statWrong: String,
    val accuracy: String,
    val toReview: String,
    val mistakeCount: (Int) -> String,
    val practiseMistakes: String,
    val done: String,
    val milestone: (Int) -> String,
    // Home and module home
    val greeting: String,
    val subtitle: String,
    val statMastered: String,
    val statStreak: String,
    val version: (String) -> String,
    val practise: String,
    val dueCount: (Int) -> String,
    val nothingDue: String,
    val home: String,
    val quickPractice: String,
    val advanced: String,
    val moduleVerbs: String,
    val moduleVocabulary: String,
    // Advanced setup
    val verbsSetupTitle: String,
    val verbsSetupHint: String,
    val vocabularySetupTitle: String,
    val vocabularySetupHint: String,
    val selectAll: String,
    val clear: String,
    val difficulty: String,
    val difficultyAll: String,
    val difficultyBeginner: String,
    val difficultyIntermediate: String,
    val difficultyAdvanced: String,
    val matching: (items: Int, due: Int) -> String,
    val startQuiz: String,
    // Language switch
    val languageLabel: String,
)

